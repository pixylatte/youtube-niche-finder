"""Pure zero-quota production outline tests for both YouTube editorial profiles."""
import pytest

from domain import production_outline as P


def request(profile="kayip"):
    kinds = ("archive", "academic") if profile == "kayip" else ("quran", "scholarly")
    return {
        "profile": profile,
        "angle": "İki farklı belge üzerinden bu konudaki anlatım farklarını karşılaştırmak",
        "referenceTitle": "Referans içerik başlığı",
        "sources": [
            {"url": "https://archival.example.org/1", "type": kinds[0], "reviewed": True},
            {"url": "https://research.example.edu/2", "type": kinds[1], "reviewed": True},
        ],
        "claimsReviewed": True,
        "rightsReviewed": True,
        "effort": "medium",
    }


@pytest.mark.parametrize("profile,duration,ratio,scene_count", [
    ("kayip", 420, "16:9", 6),
    ("islam", 60, "9:16", 5),
])
def test_creator_voiceover_and_source_first_scenes(profile, duration, ratio, scene_count):
    result = P.build(request(profile))
    assert result["planStatus"] == "outline-for-human-review"
    assert result["format"]["targetSeconds"] == duration
    assert result["format"]["aspectRatio"] == ratio
    assert result["voiceover"]["method"] == "creator-recorded-external-microphone"
    assert result["voiceover"]["recorded"] is False
    assert result["voiceover"]["durationVerified"] is False
    assert len(result["scenes"]) == scene_count
    assert result["scenes"][0]["startSeconds"] == 0
    assert result["scenes"][-1]["endSeconds"] == duration
    assert all(a["endSeconds"] == b["startSeconds"]
               for a, b in zip(result["scenes"], result["scenes"][1:]))
    assert all(scene["scriptText"] is None
               and scene["claimsVerified"] is False
               and scene["assetsAttached"] is False for scene in result["scenes"])
    assert all(step["done"] is False for step in result["checklist"])
    assert result["autoGeneratedScript"] is False
    assert result["publicationApproved"] is False
    assert result["youtubeQuotaUsed"] == 0
    assert result["llmUsed"] is False
    assert result["databaseWritten"] is False


def test_missing_verified_sources_produces_provisional_not_publishable_plan():
    data = request("islam")
    data["sources"] = []
    data["claimsReviewed"] = False
    data["rightsReviewed"] = False
    data["effort"] = "unknown"
    plan = P.build(data)
    assert plan["planStatus"] == "blocked-provisional-outline"
    assert "two-independent-source-domains-required" in plan["researchBlockers"]
    assert plan["scenes"]
    assert plan["publicationApproved"] is False
    assert plan["sourceLinksVerified"] is False
    assert plan["visuals"]["assetLicensesVerified"] is False
    assert plan["productionEffort"]["monetaryCostKnown"] is False
    assert plan["productionEffort"]["costEstimate"] is None


def test_user_angle_is_not_misrepresented_as_a_verified_fact_or_script():
    data = request()
    angle = "Arşiv kayıtlarındaki farklı ifadelerin özgün eleştirel karşılaştırması"
    data["angle"] = angle
    plan = P.build(data)
    assert plan["workingAngle"] == angle
    assert plan["angleVerification"] == "user-supplied-not-fact-checked"
    assert not any(angle in scene["narrationInstruction"] for scene in plan["scenes"])


def test_invalid_input_fails_closed_and_does_not_create_a_plan():
    payload = request()
    payload["sources"] = [{"url": "http://invalid.example/data",
                           "type": "archive", "reviewed": True}]
    with pytest.raises(ValueError):
        P.build(payload)
    payload = request()
    payload["profile"] = "unrelated"
    with pytest.raises(ValueError):
        P.build(payload)


def test_scene_visuals_are_placeholder_categories_not_asserted_assets():
    for profile in ("kayip", "islam"):
        result = P.build(request(profile))
        assert result["visuals"]["animationTool"] == "Remotion"
        assert result["visuals"]["rendered"] is False
        assert result["visuals"]["sourceProvenanceVerified"] is False
        assert result["submittedSourceCount"] == 2
        assert result["reviewedSourceDomainCount"] == 2
        assert result["sourceLinksVerified"] is False
